// RSP microcode selection for The New Tetris.
// Graphics tasks (F3DEX2) are handled by RT64; only the audio task runs on the
// recompiled RSP path. Pass get_rsp_microcode in recomp::Configuration::rsp_callbacks.
#include "librecomp/rsp.hpp"

RspExitReason aspMain(uint8_t* rdram, uint32_t ucode_addr);  // generated by RSPRecomp from aspMain.toml

RspUcodeFunc* tnt_get_rsp_microcode(const OSTask* task) {
    switch (task->t.type) {
        case M_AUDTASK:
            return aspMain;
        default:
            fprintf(stderr, "Unknown RSP task type: %u\n", task->t.type);
            return nullptr;
    }
}
